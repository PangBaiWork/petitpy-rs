/// Vendor's `unichar` (uint32_t). EOF is the all-ones sentinel —
/// matches `(unichar)(mp_uint_t)-1` in vendor C.
pub type Unichar = u32;
pub const EOF: Unichar = u32::MAX;

const TAB_SIZE: usize = 8;

// ── Reader abstraction ────────────────────────────────────────────────────
//
// Replaces vendor's mp_reader_t. The lexer doesn't care WHERE bytes
// come from — a slice, a file, an embedded blob — only how to pull
// the next byte.
//
// The Zig original uses two function pointers plus an opaque context.
// The Rust spelling is a trait object: `ByteSource::read_byte`
// returns `None` on EOF, `close` frees any underlying resource
// (called when the Lexer is dropped, mirroring `lexerFree`).
//
// Divergence: the slice reader OWNS a copy of the source bytes
// (`Vec<u8>`), where the Zig `SliceState` borrows the caller's slice.
// The copy is an allocation detail with no observable behavior —
// token streams, positions and errors are identical — and it keeps
// the Lexer free of a lifetime parameter the parser would otherwise
// have to thread through.

pub trait ByteSource {
    fn read_byte(&mut self) -> Option<u8>;
    fn close(&mut self);
}

pub struct Reader {
    inner: Box<dyn ByteSource>,
}

impl Reader {
    pub fn read_byte(&mut self) -> Option<u8> {
        self.inner.read_byte()
    }

    pub fn close(&mut self) {
        self.inner.close();
    }

    /// Slice-backed reader.
    pub fn from_slice(src: &[u8]) -> Reader {
        Reader {
            inner: Box::new(SliceSource {
                buf: src.to_vec(),
                pos: 0,
            }),
        }
    }
}

struct SliceSource {
    buf: Vec<u8>,
    pos: usize,
}

impl ByteSource for SliceSource {
    fn read_byte(&mut self) -> Option<u8> {
        if self.pos >= self.buf.len() {
            return None;
        }
        let b = self.buf[self.pos];
        self.pos += 1;
        Some(b)
    }

    fn close(&mut self) {}
}

// ── String-literal error set ──────────────────────────────────────────────
//
// Local replacement for the runtime PyError chain. The parser (caller)
// translates these into its own diagnostic surface — the lexer itself
// has no view of the diagnostic format.

/// Local replacement for the runtime `PyError` chain.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LexError {
    /// `\N{NAME}` escape (not supported in nano).
    UnicodeNameEscape,
    /// An allocation failed. Unreachable in practice: Rust allocation
    /// failure aborts the process, where the Zig side would propagate
    /// this error — the observable difference only exists under
    /// actual OOM. Kept for signature parity with the Zig
    /// `StringParseError` set.
    OutOfMemory,
}

impl fmt::Display for LexError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            LexError::UnicodeNameEscape => write!(f, "\\N{{...}} escape not supported"),
            LexError::OutOfMemory => write!(f, "out of memory"),
        }
    }
}

impl std::error::Error for LexError {}

/// `Result<T, LexError>` — the Rust spelling of Zig's
/// `StringParseError!T`.
pub type LexResult<T> = Result<T, LexError>;

// ── Lexer struct ──────────────────────────────────────────────────────────

pub struct Lexer {
    // Carried through for the parser (A3); the lexer itself never
    // dereferences it — same as the Zig original. The `allow` keeps
    // the build warning-free until the parser reads it.
    #[allow(dead_code)]
    source_name: Qstr,
    reader: Reader,

    chr0: Unichar,
    chr1: Unichar,
    chr2: Unichar,
    // FSTRINGS: saved input queue, restored when fstring args buffer
    // drains. Mirrors vendor lex->chr*_saved fields.
    chr0_saved: Unichar,
    chr1_saved: Unichar,
    chr2_saved: Unichar,

    line: usize,
    column: usize,

    emit_dent: isize,
    nested_bracket_level: i32,

    // Indent stack. The Zig original tracks alloc/num counts
    // explicitly; a Vec is the same stack with the growth handled by
    // the allocator. The bottom entry is always 0.
    indent_level: Vec<u16>,

    tok_line: usize,
    tok_column: usize,
    tok_kind: TokenKind,
    vstr: Vec<u8>,

    // FSTRINGS: extracted .format(args...) buffer + read cursor.
    fstring_args: Vec<u8>,
    fstring_args_idx: usize,

    // Soft-keyword lookahead. Empty for every input that never triggers
    // peek_line_ends_with_colon, which is all of them but `match`/`case`.
    // See `peek.rs`.
    peek_toks: Vec<peek::SavedTok>,
    peek_vstr: Vec<u8>,
    peek_idx: usize,

    debug_mode: bool,
}

impl Lexer {
    // ── Public accessors (what the parser reads) ──────────────────────

    /// The current token's kind.
    pub fn tok_kind(&self) -> TokenKind {
        self.tok_kind
    }

    /// Line of the current token (1-based).
    pub fn tok_line(&self) -> usize {
        self.tok_line
    }

    /// Column of the current token (1-based).
    pub fn tok_column(&self) -> usize {
        self.tok_column
    }

    /// Raw bytes accumulated for the current token (NAME/STRING/BYTES
    /// payload; empty for most other kinds).
    pub fn vstr(&self) -> &[u8] {
        &self.vstr
    }

    // ── next_char + indent stack ──────────────────────────────────────

    fn next_char(&mut self) {
        // C uses size_t wraparound: column starts at (size_t)-2 and the
        // three priming next_char() calls wrap it up to 1. Mirror with
        // wrapping ops.
        if self.chr0 == b'\n' as Unichar {
            self.line += 1;
            self.column = 1;
        } else if self.chr0 == b'\t' as Unichar {
            self.column = ((self.column.wrapping_sub(1).wrapping_add(TAB_SIZE) / TAB_SIZE)
                * TAB_SIZE)
                .wrapping_add(1);
        } else {
            self.column = self.column.wrapping_add(1);
        }

        self.chr0 = self.chr1;
        self.chr1 = self.chr2;

        // FSTRINGS: when injecting fstring args, read from the args
        // buffer instead of the source reader; on exhaustion, restore
        // the saved input queue.
        if self.fstring_args_idx != 0 {
            if self.fstring_args_idx < self.fstring_args.len() {
                self.chr2 = self.fstring_args[self.fstring_args_idx] as Unichar;
                self.fstring_args_idx += 1;
            } else {
                self.chr2 = 0;
            }
            if self.chr0 == 0 {
                // consumed all fstring data, restore saved input queue
                self.chr0 = self.chr0_saved;
                self.chr1 = self.chr1_saved;
                self.chr2 = self.chr2_saved;
                self.fstring_args.clear();
                self.fstring_args_idx = 0;
            }
        } else {
            self.chr2 = self.reader.read_byte().map_or(EOF, |b| b as Unichar);
        }

        if self.chr1 == b'\r' as Unichar {
            self.chr1 = b'\n' as Unichar;
            if self.chr2 == b'\n' as Unichar {
                self.chr2 = self.reader.read_byte().map_or(EOF, |b| b as Unichar);
            }
        }

        if self.chr2 == EOF && self.chr1 != EOF && self.chr1 != b'\n' as Unichar {
            self.chr2 = b'\n' as Unichar;
        }
    }

    fn indent_push(&mut self, indent: usize) {
        // Zig's @intCast panics on overflow in debug mode; mirror it.
        self.indent_level
            .push(u16::try_from(indent).expect("indent level overflow"));
    }

    fn indent_top(&self) -> usize {
        self.indent_level[self.indent_level.len() - 1] as usize
    }

    fn indent_pop(&mut self) {
        self.indent_level.pop().expect("indent stack underflow");
    }

    // ── skip_whitespace ─────────────────────────────────────────────────

    fn skip_whitespace(&mut self, stop_at_newline: bool) -> bool {
        while !self.is_end() {
            if self.is_physical_newline() {
                if stop_at_newline && self.nested_bracket_level == 0 {
                    return true;
                }
                self.next_char();
            } else if self.is_whitespace() {
                self.next_char();
            } else if self.is_char(b'#') {
                self.next_char();
                while !self.is_end() && !self.is_physical_newline() {
                    self.next_char();
                }
            } else if self.is_char_and(b'\\', b'\n') {
                self.next_char();
                self.next_char();
            } else {
                break;
            }
        }
        false
    }

    // ── Main state machine ──────────────────────────────────────────────

    /// Advance the lexer one token. The new token is exposed via the
    /// `tok_kind`, `tok_line`, `tok_column`, `vstr` accessors.
    /// (Serves the soft-keyword lookahead buffer first when one is
    /// live; see `peek.rs` for `to_next`.)
    pub(crate) fn scan_next(&mut self) -> LexResult<()> {
        self.vstr.clear();

        let had_physical_newline = self.skip_whitespace(true);

        self.tok_line = self.line;
        self.tok_column = self.column;

        if self.emit_dent < 0 {
            self.tok_kind = TokenKind::DEDENT;
            self.emit_dent += 1;
        } else if self.emit_dent > 0 {
            self.tok_kind = TokenKind::INDENT;
            self.emit_dent -= 1;
        } else if had_physical_newline {
            let _ = self.skip_whitespace(false);

            self.tok_kind = TokenKind::NEWLINE;

            let num_spaces = self.column - 1;
            if num_spaces == self.indent_top() {
                // same level
            } else if num_spaces > self.indent_top() {
                self.indent_push(num_spaces);
                self.emit_dent += 1;
            } else {
                while num_spaces < self.indent_top() {
                    self.indent_pop();
                    self.emit_dent -= 1;
                }
                if num_spaces != self.indent_top() {
                    self.tok_kind = TokenKind::DEDENT_MISMATCH;
                }
            }
        } else if self.is_end() {
            self.tok_kind = TokenKind::END;
        } else if self.is_string_or_bytes() {
            self.tok_kind = TokenKind::END;

            loop {
                let mut is_raw = false;
                let mut is_fstring = false;
                let mut kind = TokenKind::STRING;
                let mut n_char: i32 = 0;
                if self.is_char(b'u') {
                    n_char = 1;
                } else if self.is_char(b'b') {
                    kind = TokenKind::BYTES;
                    n_char = 1;
                    if self.is_char_following(b'r') {
                        is_raw = true;
                        n_char = 2;
                    }
                } else if self.is_char(b'r') {
                    is_raw = true;
                    n_char = 1;
                    if self.is_char_following(b'b') {
                        kind = TokenKind::BYTES;
                        n_char = 2;
                    } else if self.is_char_following(b'f') {
                        is_fstring = true;
                        n_char = 2;
                    }
                } else if self.is_char(b'f') {
                    is_fstring = true;
                    n_char = 1;
                    if self.is_char_following(b'r') {
                        is_raw = true;
                        n_char = 2;
                    }
                }

                if self.tok_kind == TokenKind::END {
                    self.tok_kind = kind;
                } else if self.tok_kind != kind {
                    break;
                }

                if n_char != 0 {
                    self.next_char();
                    if n_char == 2 {
                        self.next_char();
                    }
                }

                self.parse_string_literal_inner(is_raw, is_fstring)?;

                let _ = self.skip_whitespace(true);

                if !self.is_string_or_bytes() {
                    break;
                }
            }

            // FSTRINGS: at end-of-fstring token, switch input source
            // to the .format(args...) buffer we've been building.
            if !self.fstring_args.is_empty() && self.fstring_args_idx == 0 {
                self.fstring_args.push(b')');
                self.chr0_saved = self.chr0;
                self.chr1_saved = self.chr1;
                self.chr2_saved = self.chr2;
                self.chr0 = self.fstring_args[0] as Unichar;
                self.chr1 = if self.fstring_args.len() > 1 {
                    self.fstring_args[1] as Unichar
                } else {
                    0
                };
                self.chr2 = if self.fstring_args.len() > 2 {
                    self.fstring_args[2] as Unichar
                } else {
                    0
                };
                self.fstring_args_idx = 3;
            }
        } else if self.is_head_of_identifier() {
            self.tok_kind = TokenKind::NAME;

            self.vstr.push((self.cur() & 0xff) as u8);
            self.next_char();

            while !self.is_end() && self.is_tail_of_identifier() {
                self.vstr.push((self.cur() & 0xff) as u8);
                self.next_char();
            }

            // Keyword lookup with C strcmp semantics. The Zig side
            // appends a NUL to the vstr and compares against
            // NUL-terminated keywords; `strcmp_slice` treats the end
            // of each slice as the NUL, which is exactly equivalent,
            // and the vstr is left untouched (the Zig code pops the
            // NUL before returning).
            for (i, kw) in TOK_KW.iter().enumerate() {
                let cmp = strcmp_slice(&self.vstr, kw.as_bytes());
                if cmp == 0 {
                    self.tok_kind = TokenKind::from_u8(TokenKind::KW_FALSE as u8 + i as u8)
                        .expect("keyword kind in range");
                    if self.tok_kind == TokenKind::KW___DEBUG__ {
                        self.tok_kind = if self.debug_mode {
                            TokenKind::KW_TRUE
                        } else {
                            TokenKind::KW_FALSE
                        };
                    }
                    break;
                } else if cmp < 0 {
                    break;
                }
            }
        } else if self.is_digit_p() || (self.is_char(b'.') && self.is_following_digit()) {
            let mut forced_integer = false;
            if self.is_char(b'.') {
                self.tok_kind = TokenKind::FLOAT_OR_IMAG;
            } else {
                self.tok_kind = TokenKind::INTEGER;
                if self.is_char(b'0') && self.is_following_base_char() {
                    forced_integer = true;
                }
            }

            self.vstr.push((self.cur() & 0xff) as u8);
            self.next_char();

            while !self.is_end() {
                if !forced_integer && self.is_char_or(b'e', b'E') {
                    self.tok_kind = TokenKind::FLOAT_OR_IMAG;
                    self.vstr.push(b'e');
                    self.next_char();
                    if self.is_char(b'+') || self.is_char(b'-') {
                        self.vstr.push((self.cur() & 0xff) as u8);
                        self.next_char();
                    }
                } else if self.is_letter() || self.is_digit_p() || self.is_char(b'.') {
                    if self.is_char_or3(b'.', b'j', b'J') {
                        self.tok_kind = TokenKind::FLOAT_OR_IMAG;
                    }
                    self.vstr.push((self.cur() & 0xff) as u8);
                    self.next_char();
                } else if self.is_char(b'_') {
                    self.next_char();
                } else {
                    break;
                }
            }
        } else {
            // Encoded delimiter / operator scan.
            let mut ti: usize = 0; // index into TOK_ENC
            let mut tok_enc_index: usize = 0;
            while tok_enc_at(ti) != 0 && !self.is_char(tok_enc_at(ti)) {
                if tok_enc_at(ti) == b'e' || tok_enc_at(ti) == b'c' {
                    ti += 1;
                }
                tok_enc_index += 1;
                ti += 1;
            }

            self.next_char();

            if tok_enc_at(ti) == 0 {
                self.tok_kind = TokenKind::INVALID;
            } else if tok_enc_at(ti) == b'!' {
                if self.is_char(b'=') {
                    self.next_char();
                    self.tok_kind = TokenKind::OP_NOT_EQUAL;
                } else {
                    self.tok_kind = TokenKind::INVALID;
                }
            } else if tok_enc_at(ti) == b'.' {
                if self.is_char_and(b'.', b'.') {
                    self.next_char();
                    self.next_char();
                    self.tok_kind = TokenKind::ELLIPSIS;
                } else {
                    self.tok_kind = TokenKind::DEL_PERIOD;
                }
            } else {
                ti += 1;
                let mut t_index = tok_enc_index;
                while tok_enc_at(ti) == b'c' || tok_enc_at(ti) == b'e' {
                    t_index += 1;
                    if self.is_char(tok_enc_at(ti + 1)) {
                        self.next_char();
                        tok_enc_index = t_index;
                        if tok_enc_at(ti) == b'e' {
                            break;
                        }
                    } else if tok_enc_at(ti) == b'c' {
                        break;
                    }
                    ti += 2;
                }

                self.tok_kind = TOK_ENC_KIND[tok_enc_index];

                if matches!(
                    self.tok_kind,
                    TokenKind::DEL_PAREN_OPEN
                        | TokenKind::DEL_BRACKET_OPEN
                        | TokenKind::DEL_BRACE_OPEN
                ) {
                    self.nested_bracket_level += 1;
                } else if matches!(
                    self.tok_kind,
                    TokenKind::DEL_PAREN_CLOSE
                        | TokenKind::DEL_BRACKET_CLOSE
                        | TokenKind::DEL_BRACE_CLOSE
                ) {
                    self.nested_bracket_level -= 1;
                }
            }
        }
        Ok(())
    }

    // ── Constructors / destructor ─────────────────────────────────────────

    /// Allocate and prime a new Lexer reading from `reader`.
    ///
    /// `source_name` is a pre-interned qstr id naming the source. The
    /// lexer never dereferences it — it's just carried through for the
    /// parser.
    ///
    /// `debug_mode` is true under the unoptimised (default) Python
    /// settings and turns `__debug__` into a KW_TRUE literal. Set to
    /// false to emit KW_FALSE (i.e. behave as if -O was passed).
    pub fn new(source_name: Qstr, reader: Reader, debug_mode: bool) -> LexResult<Lexer> {
        Self::new_internal(source_name, reader, debug_mode)
    }

    /// Convenience: construct a Lexer reading from an in-memory byte
    /// slice. The slice is copied (see the `Reader` docs); the
    /// returned Lexer owns the copy.
    pub fn new_from_str(source_name: Qstr, src: &[u8], debug_mode: bool) -> LexResult<Lexer> {
        Self::new_internal(source_name, Reader::from_slice(src), debug_mode)
    }

    fn new_internal(source_name: Qstr, reader: Reader, debug_mode: bool) -> LexResult<Lexer> {
        let mut l = Lexer {
            source_name,
            reader,
            chr0: 0,
            chr1: 0,
            chr2: 0,
            chr0_saved: 0,
            chr1_saved: 0,
            chr2_saved: 0,
            line: 1,
            column: usize::MAX - 1, // priming wrap — see next_char header
            emit_dent: 0,
            nested_bracket_level: 0,
            indent_level: vec![0u16],
            tok_line: 0,
            tok_column: 0,
            tok_kind: TokenKind::END,
            vstr: Vec::new(),
            fstring_args: Vec::new(),
            fstring_args_idx: 0,
            peek_toks: Vec::new(),
            peek_vstr: Vec::new(),
            peek_idx: 0,
            debug_mode,
        };

        // Prime the 3-char lookahead and zero out the vstr.
        l.next_char();
        l.next_char();
        l.next_char();

        l.to_next()?;

        // Vendor lexer.c: any token that doesn't start in column 1 (and
        // isn't a NEWLINE) becomes an implicit INDENT at the file head.
        if l.tok_column != 1 && l.tok_kind != TokenKind::NEWLINE {
            l.tok_kind = TokenKind::INDENT;
        }

        Ok(l)
    }
}

impl Drop for Lexer {
    /// Mirrors `lexerFree`: calls `reader.close()` before the struct's
    /// storage is dropped (Rust drops the Vecs automatically).
    fn drop(&mut self) {
        self.reader.close();
    }
}
