//! Compiler-track lexer — pure Rust Python tokeniser.
//!
//! Port of `src/compiler/lexer.zig`. Key divergences from the legacy
//! frontend lexer, mirroring the divergences the Zig file itself
//! documents against vendor `py/lexer.c`:
//!
//!   1. No `@cImport` (the brief's premise was wrong — the only
//!      `@cImport` in `lexer.zig` is the word itself in a comment;
//!      see `scripts/a2_result.txt`). The `mp_token_kind_t` enum is
//!      mirrored locally as `TokenKind` with the exact same ordinal
//!      layout (`tables.rs`); a compile-time fingerprint check
//!      (NUMBER_OF == 96) catches accidental drift if the vendor
//!      enum grows.
//!   2. All C-runtime couplings removed: vstr -> `Vec<u8>`,
//!      m_malloc/m_realloc -> Rust allocation, unichar_is* -> inline
//!      ASCII predicates (`chars.rs`), mp_reader_t -> the `Reader`
//!      trait-object below, npy_optimise_value() -> the `debug_mode`
//!      field set by the caller at construction time.
//!   3. No C-ABI exports. Public API is pure Rust: `Lexer::new`,
//!      `Lexer::new_from_str`, `Lexer::to_next`.
//!   4. No qstr interning inside the lexer. The lexer is a pure
//!      tokeniser and accumulates raw NAME/STRING/BYTES bytes into
//!      `Lexer::vstr`; the parser calls `qstr_from_strn` on
//!      consumption. The ONE qstr touch-point is `Lexer::source_name`
//!      (set by caller at construction time), and even that is just
//!      a `u16` field — `qstr` is imported only for the type alias.
//!   5. No `PyError` dependency. The runtime error machinery is
//!      replaced with a local `LexError` set.
//!
//! Algorithm is a verbatim port of vendor py/lexer.c, preserving the
//! 3-char lookahead state machine, CRLF normalisation, tab expansion,
//! indent-stack push/pop, and the encoded operator/delimiter scanner.
//!
//! FSTRINGS are enabled (port/mpconfigport.h: MICROPY_PY_FSTRINGS=1)
//! so the f-string args-buffer apparatus is included. ASYNC_AWAIT is
//! enabled under both nano and full (port/mpconfigport.h:
//! MICROPY_PY_ASYNC_AWAIT=1) — KW_ASYNC and KW_AWAIT are unconditional
//! slots between KW_ASSERT and KW_BREAK.
//!
//! Invariant the compiler-track lexer must hold: token streams must be
//! byte-identical to vendor `py/lexer.c` across the corpus, validated
//! by the differential test harness (`lexer_test.zig` +
//! `scripts/check_lexer_corpus.py`; the vendor `token_dump` harness
//! itself is deferred upstream — see `scripts/a2_result.txt`).
//!
//! Layout: this file holds the `Lexer` struct, the `Reader`
//! abstraction, `next_char`, the indent stack, `skip_whitespace`,
//! the main state machine (`scan_next`) and the constructors. The
//! Zig file's other sections live in submodules so no file exceeds
//! 800 lines: `tables.rs` (TokenKind + encoding/keyword tables),
//! `chars.rs` (character predicates), `string.rs` (string-literal
//! scanning), `peek.rs` (soft-keyword lookahead), `tests.rs` (ported
//! unit tests).

