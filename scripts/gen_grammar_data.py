#!/usr/bin/env python3
"""Generate src/compiler/grammar_data.rs from the Zig original.

Usage: python3 scripts/gen_grammar_data.py

Reads petitpy-orig/src/compiler/grammar_data.zig (itself AUTO-GENERATED
by tools/gen_grammar.py from vendor/micropython_embed/py/grammar.h —
SHA-256 pinned in the Zig file header) and emits the Rust transliteration.
The translation is mechanical: every constant and every table entry is
copied verbatim; only the formatting changes (tables are packed 8 entries
per line so the file stays under the 800-line rule). Correctness is
checked independently by scripts/check_grammar_data.py, which re-parses
both files and diffs every value — never by eyeballing.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ZIG = ROOT.parent / "petitpy-orig" / "src" / "compiler" / "grammar_data.zig"
OUT = ROOT / "src" / "compiler" / "grammar_data.rs"


def parse_table(src: str, name: str, typ: str) -> list[int]:
    m = re.search(r"pub const " + name + r" = \[_\]" + typ + r"\{([^}]*)\};", src, re.S)
    assert m, f"table {name} not found"
    return [int(v, 16) for v in re.findall(r"0x[0-9a-fA-F]+", m.group(1))]


def parse_consts(src: str):
    rules = re.findall(r"pub const (RULE_\w+): u8 = (\d+);", src)
    assert rules, "no RULE_* constants found"
    return [(name, int(v)) for name, v in rules]


def parse_scalar(src: str, name: str, typ: str) -> str:
    m = re.search(r"pub const " + name + r": " + typ + r" = (0x[0-9a-fA-F]+|\d+);", src)
    assert m, f"scalar {name} not found"
    return m.group(1)


def emit_table(name: str, typ: str, vals: list[int], per_line: int = 8) -> list[str]:
    lines = [f"pub const {name}: &[{typ}; {len(vals)}] = &["]
    for i in range(0, len(vals), per_line):
        chunk = vals[i : i + per_line]
        rendered = ", ".join(f"0x{v:02x}" if v <= 0xFF else f"0x{v:04x}" for v in chunk)
        lines.append(f"    {rendered}, // [{i}]")
    lines.append("];")
    return lines


def main() -> int:
    src = ZIG.read_text()
    zig_sha = re.search(r"SHA-256: ([0-9a-f]+)", src).group(1)

    num_rules = parse_scalar(src, "NUM_RULES", "usize")
    first_above = parse_scalar(src, "FIRST_RULE_WITH_OFFSET_ABOVE_255", "u8")
    masks = []
    for name in [
        "RULE_ACT_ARG_MASK",
        "RULE_ACT_KIND_MASK",
        "RULE_ACT_ALLOW_IDENT",
        "RULE_ACT_ADD_BLANK",
        "RULE_ACT_OR",
        "RULE_ACT_AND",
        "RULE_ACT_LIST",
    ]:
        masks.append((name, parse_scalar(src, name, "u8")))
    arg_masks = []
    for name in [
        "RULE_ARG_KIND_MASK",
        "RULE_ARG_ARG_MASK",
        "RULE_ARG_TOK",
        "RULE_ARG_RULE",
        "RULE_ARG_OPT_RULE",
    ]:
        arg_masks.append((name, parse_scalar(src, name, "u16")))

    rules = parse_consts(src)
    act = parse_table(src, "rule_act_table", "u8")
    comb = parse_table(src, "rule_arg_combined_table", "u16")
    off = parse_table(src, "rule_arg_offset_table", "u8")

    assert len(rules) == int(num_rules), f"RULE_* count {len(rules)} != NUM_RULES"
    assert len(act) == int(num_rules)
    assert len(off) == int(num_rules)
    assert len(comb) == 467, f"combined table length drift: {len(comb)}"

    out: list[str] = []
    out.append("//! Grammar tables for the MicroPython parser — Rust port.")
    out.append("//!")
    out.append("//! GENERATED by `scripts/gen_grammar_data.py` from")
    out.append("//! `petitpy-orig/src/compiler/grammar_data.zig` — DO NOT EDIT BY HAND.")
    out.append("//! The Zig file is itself AUTO-GENERATED by `tools/gen_grammar.py`")
    out.append("//! from `vendor/micropython_embed/py/grammar.h`")
    out.append(f"//! (SHA-256: {zig_sha}).")
    out.append("//!")
    out.append("//! Every constant and table entry is copied verbatim; only the")
    out.append("//! formatting changes (tables are packed 8 entries per line so")
    out.append("//! this file stays under the 800-line rule). Correctness is")
    out.append("//! verified by `scripts/check_grammar_data.py`, which re-parses")
    out.append("//! both files and diffs every value, plus the structural tests")
    out.append("//! at the bottom of this file.")
    out.append("#![allow(non_upper_case_globals)]")
    out.append("// Rule-id constants keep their exact Zig/vendor names (`RULE_file_input`,")
    out.append("// `RULE_yield_arg_from`, ...) instead of Rust UPPER_SNAKE_CASE: the")
    out.append("// names are load-bearing identifiers shared with grammar.h, the Zig")
    out.append("// original, and the parser/compiler phases that dispatch over them.")
    out.append("// Renaming them would break line-by-line checkability against the")
    out.append("// original, so the lint is silenced for this file only, deliberately.")
    out.append("")
    out.append(f"pub const NUM_RULES: usize = {num_rules};")
    out.append(
        f"pub const FIRST_RULE_WITH_OFFSET_ABOVE_255: u8 = {first_above};"
    )
    out.append("")
    out.append("// rule_act bit masks (lifted from py/parse.c).")
    for name, val in masks:
        out.append(f"pub const {name}: u8 = {val};")
    out.append("")
    out.append("// rule_arg bit masks.")
    for name, val in arg_masks:
        out.append(f"pub const {name}: u16 = {val};")
    out.append("")
    out.append("// Rule-id constants — one per active grammar rule, plus const_object.")
    out.append("// Both the parser and the compiler dispatch over these names.")
    for name, val in rules:
        out.append(f"pub const {name}: u8 = {val};")
    out.append("")
    out.append("// ── rule_act_table ──────────────────────────────────────────────")
    out.extend(emit_table("RULE_ACT_TABLE", "u8", act))
    out.append("")
    out.append("// ── rule_arg_combined_table ─────────────────────────────────────")
    out.extend(emit_table("RULE_ARG_COMBINED_TABLE", "u16", comb))
    out.append("")
    out.append("// ── rule_arg_offset_table ───────────────────────────────────────")
    out.append("// Low 8 bits of each rule's offset into RULE_ARG_COMBINED_TABLE.")
    out.append("// The 9th bit is set by get_rule_arg() when id >=")
    out.append("// FIRST_RULE_WITH_OFFSET_ABOVE_255.")
    out.extend(emit_table("RULE_ARG_OFFSET_TABLE", "u8", off))
    out.append("")
    out.append("// ── accessors (mirror py/parse.c npy_rule_act / get_rule_arg) ───")
    out.append("/// Effective offset of rule `id` into RULE_ARG_COMBINED_TABLE.")
    out.append("pub fn rule_arg_offset(id: u8) -> usize {")
    out.append("    let mut off = RULE_ARG_OFFSET_TABLE[id as usize] as usize;")
    out.append("    if id >= FIRST_RULE_WITH_OFFSET_ABOVE_255 {")
    out.append("        off |= 0x100;")
    out.append("    }")
    out.append("    off")
    out.append("}")
    out.append("")
    out.append("/// The rule action byte for rule `id` (mirrors `ruleAct`).")
    out.append("pub fn rule_act(id: u8) -> u8 {")
    out.append("    RULE_ACT_TABLE[id as usize]")
    out.append("}")
    out.append("")
    out.append("/// The argument list of rule `id` (mirrors `getRuleArg`).")
    out.append("///")
    out.append("/// The Zig original returns a raw `[*]const u16` pointer and the")
    out.append("/// caller reads `rule_act(id) & RULE_ACT_ARG_MASK` entries from it")
    out.append("/// (vendor parse.c:1098-1099). The Rust version returns exactly")
    out.append("/// that many entries as a slice, so the bound is checked here.")
    out.append("///")
    out.append("/// NOTE: rule spans are NOT a contiguous partition of the combined")
    out.append("/// table — by construction (the vendor's RULE_PADDING enum) 35")
    out.append("/// rules overlap the next rule's span by one entry or leave a")
    out.append("/// one-entry gap, so no `offset(id) + count(id) == offset(id+1)`")
    out.append("/// invariant holds. The only invariant is that every rule's")
    out.append("/// `[offset, offset + count)` lies inside the combined table;")
    out.append("/// the test below asserts exactly that.")
    out.append("pub fn get_rule_arg(id: u8) -> &'static [u16] {")
    out.append("    let off = rule_arg_offset(id);")
    out.append("    let count = (rule_act(id) & RULE_ACT_ARG_MASK) as usize;")
    out.append("    &RULE_ARG_COMBINED_TABLE[off..off + count]")
    out.append("}")
    out.append("")
    out.append("#[cfg(test)]")
    out.append("mod tests {")
    out.append("    use super::*;")
    out.append("")
    out.append("    #[test]")
    out.append("    fn tables_have_num_rules_entries() {")
    out.append("        assert_eq!(183, NUM_RULES);")
    out.append("        assert_eq!(NUM_RULES, RULE_ACT_TABLE.len());")
    out.append("        assert_eq!(NUM_RULES, RULE_ARG_OFFSET_TABLE.len());")
    out.append("        assert_eq!(467, RULE_ARG_COMBINED_TABLE.len());")
    out.append("    }")
    out.append("")
    out.append("    #[test]")
    out.append("    fn rule_id_constants_spot_check() {")
    out.append("        assert_eq!(0, RULE_file_input);")
    out.append("        assert_eq!(59, RULE_const_object);")
    out.append("        assert_eq!(101, RULE_import_from_2b);")
    out.append("        assert_eq!(150, RULE_atom);")
    out.append("        assert_eq!(182, RULE_yield_arg_from);")
    out.append("    }")
    out.append("")
    out.append("    #[test]")
    out.append("    fn rule_act_spot_check() {")
    out.append("        assert_eq!(0x61, rule_act(RULE_file_input));")
    out.append("        assert_eq!(0xa8, rule_act(RULE_funcdef));")
    out.append("        assert_eq!(0x00, rule_act(RULE_const_object));")
    out.append("        assert_eq!(0x1d, rule_act(RULE_augassign));")
    out.append("        assert_eq!(0x64, rule_act(RULE_suite_block));")
    out.append("        assert_eq!(0x22, rule_act(RULE_yield_arg_from));")
    out.append("    }")
    out.append("")
    out.append("    #[test]")
    out.append("    fn every_rule_arg_slice_is_in_bounds() {")
    out.append("        // The only structural invariant the vendor table offers:")
    out.append("        // every rule's [offset, offset + count) lies inside the")
    out.append("        // combined table. (Spans are not contiguous — see the")
    out.append("        // note on get_rule_arg — so no equality is asserted.)")
    out.append("        for id in 0..NUM_RULES as u8 {")
    out.append("            let args = get_rule_arg(id);")
    out.append("            assert_eq!((rule_act(id) & RULE_ACT_ARG_MASK) as usize, args.len());")
    out.append("        }")
    out.append("        // The last rule's span ends exactly at the table end.")
    out.append("        assert_eq!(")
    out.append("            RULE_ARG_COMBINED_TABLE.len(),")
    out.append("            rule_arg_offset(RULE_yield_arg_from)")
    out.append("                + (rule_act(RULE_yield_arg_from) & RULE_ACT_ARG_MASK) as usize")
    out.append("        );")
    out.append("    }")
    out.append("")
    out.append("    #[test]")
    out.append("    fn get_rule_arg_spot_check() {")
    out.append("        assert_eq!(&[0x3001u16], get_rule_arg(RULE_file_input));")
    out.append("        assert_eq!(")
    out.append("            &[0x101a, 0x1008, 0x1054, 0x3047, 0x1055, 0x3046, 0x105b, 0x2083],")
    out.append("            get_rule_arg(RULE_funcdef)")
    out.append("        );")
    out.append("        assert_eq!(&[] as &[u16], get_rule_arg(RULE_const_object));")
    out.append("        assert_eq!(&[0x206f, 0x2065], get_rule_arg(RULE_import_from_2));")
    out.append("        assert_eq!(&[0x1021, 0x2086], get_rule_arg(RULE_yield_arg_from));")
    out.append("        // Overlapping spans are real: rule 1 shares its last entry")
    out.append("        // with rule 2's first (vendor table construction).")
    out.append("        assert_eq!(&[0x203f, 0x2043], get_rule_arg(RULE_file_input_2));")
    out.append("        assert_eq!(&[0x2043, 0x2044], get_rule_arg(RULE_decorated));")
    out.append("    }")
    out.append("}")
    out.append("")

    OUT.write_text("\n".join(out))
    print(f"wrote {OUT} ({len(out)} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
