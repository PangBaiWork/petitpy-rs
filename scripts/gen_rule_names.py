#!/usr/bin/env python3
"""Generate src/compiler/parser/names.rs — rule-id -> short name.

Reads the RULE_* constants from src/compiler/grammar_data.rs (183
vendor rules) and src/compiler/grammar_ext.rs (9 extension rules) and
emits a `rule_name(id) -> &'static str` match, the Rust equivalent of
the reflection-built `rule_names` table in parser.zig's tests (which
strips the `RULE_` prefix and prints "?" for unknown ids).

The generated file is checked in (like grammar_data.rs) so the build
does not depend on this script; re-run it if the grammar changes and
diff the output.

Usage: python3 scripts/gen_rule_names.py
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

def main() -> int:
    names: dict[int, str] = {}
    gd = (ROOT / "src" / "compiler" / "grammar_data.rs").read_text()
    for m in re.finditer(r"^pub const (RULE_[a-zA-Z0-9_]+): u8 = (\d+);", gd, re.M):
        name, num = m.group(1), int(m.group(2))
        if num in names:
            print(f"ERROR: duplicate rule id {num}: {names[num]} vs {name}")
            return 1
        names[num] = name[5:]  # strip RULE_
    if len(names) != 183:
        print(f"ERROR: expected 183 vendor rules, found {len(names)}")
        return 1

    # Extension rules: values are expressions off NUM_RULES.
    ge = (ROOT / "src" / "compiler" / "grammar_ext.rs").read_text()
    ext: dict[str, int] = {}
    base = 183
    for m in re.finditer(r"^pub const (RULE_[a-zA-Z0-9_]+): u8 = (.+);", ge, re.M):
        name, expr = m.group(1), m.group(2).strip()
        if expr == "grammar::NUM_RULES as u8":
            val = base
        elif expr.startswith("RULE_match_stmt + "):
            val = base + int(expr.split("+")[1])
        else:
            print(f"ERROR: cannot evaluate ext rule expr: {expr}")
            return 1
        if val in names:
            print(f"ERROR: duplicate rule id {val}: {names[val]} vs {name}")
            return 1
        names[val] = name[5:]
        ext[name] = val
    if len(ext) != 9:
        print(f"ERROR: expected 9 extension rules, found {len(ext)}")
        return 1

    out = []
    out.append("//! Rule-id -> short name, for readable tree dumps.")
    out.append("//!")
    out.append("//! Generated by `scripts/gen_rule_names.py` from the RULE_*")
    out.append("//! constants in `grammar_data.rs` (183 vendor rules) and")
    out.append("//! `grammar_ext.rs` (9 extension rules). Do not hand-edit;")
    out.append("//! re-run the generator and diff the output instead.")
    out.append("//!")
    out.append("//! Mirrors the reflection-built `rule_names` table in")
    out.append("//! parser.zig's tests (strips the `RULE_` prefix, \"?\" for")
    out.append("//! unknown ids).")
    out.append("")
    out.append("/// Short name of rule `id` (without the `RULE_` prefix),")
    out.append("/// or \"?\" when `id` is not a known rule.")
    out.append("///")
    out.append("/// Test-only: the only consumer is the test dump in")
    out.append("/// `parser/tests.rs` (mirroring parser.zig, where the")
    out.append("/// rule_names table is built for the tests).")
    out.append("#[cfg(test)]")
    out.append("pub fn rule_name(id: u8) -> &'static str {")
    out.append("    match id {")
    for num in sorted(names):
        out.append(f"        {num} => \"{names[num]}\",")
    out.append("        _ => \"?\",")
    out.append("    }")
    out.append("}")
    out.append("")
    target = ROOT / "src" / "compiler" / "parser" / "names.rs"
    target.write_text("\n".join(out))
    print(f"wrote {target} ({len(names)} rules: 183 vendor + 9 ext)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
